// TestSizecheckPolicy verifies the file-size gate's limits, skips and ratchet.
//
// Why it matters: the budget in AGENTS.md was convention-only; a gate that
// misreads a limit, a generated file or an exception would either block every
// PR or enforce nothing.
// Inputs: small synthetic trees with files of controlled lengths plus an
// exceptions file. Outputs: exit status and the message naming the verdict.
// Data choice: each case sits exactly on a boundary (299/300, 799/800, cap vs
// cap+1) or exercises one skip rule (vendor, generated) or one ratchet rule
// (grew, stale, back under budget).
func TestSizecheckPolicy(t *testing.T) {
	const generated = "// Code generated by oapi-codegen DO NOT EDIT.\n"
	cases := []struct {
		name       string
		files      map[string]int // path -> line count
		generated  []string       // paths that carry the generated header
		exceptions string
		wantExit   int
		wantText   string
	}{
		{"under budget", map[string]int{"a.go": 299, "a_test.go": 799}, nil, "", 0, "2 file(s) within budget (0 excepted)"},
		{"production at limit", map[string]int{"big.go": 300}, nil, "", 1, "OVER big.go: 300 lines (budget < 300)"},
		{"test at limit", map[string]int{"big_test.go": 800}, nil, "", 1, "OVER big_test.go: 800 lines (budget < 800)"},
		{"vendor skipped", map[string]int{"vendor/x/huge.go": 5000}, nil, "", 0, "0 file(s) within budget"},
		{"generated skipped", map[string]int{"api.go": 5000}, []string{"api.go"}, "", 0, "0 file(s) within budget"},
		{"excepted at cap", map[string]int{"old.go": 450}, nil, "old.go 450", 0, "1 file(s) within budget (1 excepted)"},
		{"excepted grew", map[string]int{"old.go": 451}, nil, "old.go 450 # frozen", 1, "GREW old.go: 451 lines, exception allows 450"},
		{"excepted back under budget", map[string]int{"old.go": 120}, nil, "old.go 450", 0, "note: old.go is 120 lines, under the 300-line budget"},
		{"stale exception", map[string]int{"a.go": 10}, nil, "gone.go 450", 1, "STALE exception gone.go"},
		{"invalid exception", map[string]int{"a.go": 10}, nil, "a.go many", 1, "invalid size exception"},
	}
	for _, testCase := range cases {
		t.Run(testCase.name, func(t *testing.T) {
			output, exitCode := runSizecheck(t, testCase.files, testCase.generated, generated, testCase.exceptions)
			if exitCode != testCase.wantExit {
				t.Errorf("exit = %d, want %d; output:\n%s", exitCode, testCase.wantExit, output)
			}
			if !strings.Contains(output, testCase.wantText) {
				t.Errorf("output = %q, want %q", output, testCase.wantText)
			}
		})
	}
}

func runSizecheck(t *testing.T, files map[string]int, generated []string, header, exceptions string) (string, int) {
	t.Helper()
	root := t.TempDir()
	writeSizeFixture(t, root, files, generated, header)
	exceptionsPath := filepath.Join(root, "exceptions.txt")
	if err := os.WriteFile(exceptionsPath, []byte(exceptions+"\n"), 0600); err != nil {
		t.Fatal(err)
	}
	command := exec.Command("sh", "./sizecheck.sh")
	command.Env = append(os.Environ(), "SIZE_ROOT="+root, "SIZE_EXCEPTIONS="+exceptionsPath)
	result, err := command.CombinedOutput()
	if err == nil {
		return string(result), 0
	}
	var exitError *exec.ExitError
	if !errors.As(err, &exitError) {
		t.Fatalf("running sizecheck: %v", err)
	}
	return string(result), exitError.ExitCode()
}

// writeSizeFixture creates one file per entry with the requested line count,
// giving the generated ones the DO NOT EDIT header as their first line.
func writeSizeFixture(t *testing.T, root string, files map[string]int, generated []string, header string) {
	t.Helper()
	isGenerated := map[string]bool{}
	for _, path := range generated {
		isGenerated[path] = true
	}
	for path, lines := range files {
		content := strings.Repeat("// line\n", lines)
		if isGenerated[path] {
			content = header + content[len("// line\n"):]
		}
		full := filepath.Join(root, path)
		if err := os.MkdirAll(filepath.Dir(full), 0700); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(content), 0600); err != nil {
			t.Fatal(err)
		}
	}
}
